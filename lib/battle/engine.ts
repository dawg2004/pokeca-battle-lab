import type { DeckList } from "@/lib/deck/types";
import type { BattleCard, BattleLogEntry, BattleSetup, BattleState, LegalAction, PlayerId, Zone } from "./types";

const playerIds: PlayerId[] = ["player", "opponent"];

function mulberry32(seed: number) {
  return () => {
    let t = (seed += 0x6d2b79f5);
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function expandDeck(deck: DeckList, owner: PlayerId): BattleCard[] {
  return deck.entries.flatMap((entry) =>
    Array.from({ length: entry.count }, (_, index) => ({
      ...entry.card,
      instanceId: `${owner}-${entry.card.id}-${index}`,
      attachedEnergy: 0,
      damage: 0,
      turnPlayed: 0,
      evolvedThisTurn: false,
      abilityUsedThisTurn: false,
      tool: null,
      previousStages: []
    }))
  );
}

function shuffle<T>(items: T[], seed: number): T[] {
  const random = mulberry32(seed);
  const copy = [...items];
  for (let i = copy.length - 1; i > 0; i -= 1) {
    const j = Math.floor(random() * (i + 1));
    [copy[i], copy[j]] = [copy[j], copy[i]];
  }
  return copy;
}

function draw(zone: Zone, count: number): BattleCard[] {
  const drawn = zone.deck.slice(0, count);
  zone.deck = zone.deck.slice(count);
  zone.hand = [...zone.hand, ...drawn];
  return drawn;
}

function pushLog(state: BattleState, actor: PlayerId, message: string): void {
  const entry: BattleLogEntry = {
    id: `${state.turn}-${state.log.length}-${actor}`,
    turn: state.turn,
    actor,
    message
  };
  state.log = [entry, ...state.log].slice(0, 80);
}

const MAX_MULLIGAN_ATTEMPTS = 20;

function hasBasicPokemon(cards: BattleCard[]): boolean {
  return cards.some((card) => card.category === "pokemon" && card.isBasic);
}

type ZoneSetup = {
  zone: Zone;
  mulligans: number;
};

function setupZone(deck: DeckList, owner: PlayerId, seed: number): ZoneSetup {
  const pool = expandDeck(deck, owner);
  let shuffled = shuffle(pool, seed);
  let mulligans = 0;

  while (!hasBasicPokemon(shuffled.slice(0, 7)) && mulligans < MAX_MULLIGAN_ATTEMPTS && hasBasicPokemon(pool)) {
    mulligans += 1;
    shuffled = shuffle(pool, seed + mulligans * 7919);
  }

  const zone: Zone = {
    deck: shuffled,
    hand: [],
    active: null,
    bench: [],
    discard: [],
    prizes: [],
    prizeTaken: 0
  };
  draw(zone, 7);
  zone.prizes = zone.deck.slice(0, 6);
  zone.deck = zone.deck.slice(6);

  const activeIndex = zone.hand.findIndex((card) => card.category === "pokemon" && card.isBasic);
  if (activeIndex >= 0) {
    const [active] = zone.hand.splice(activeIndex, 1);
    zone.active = { ...active, turnPlayed: 1 };
  }

  while (zone.bench.length < 2) {
    const benchIndex = zone.hand.findIndex((card) => card.category === "pokemon" && card.isBasic);
    if (benchIndex < 0) break;
    const [basic] = zone.hand.splice(benchIndex, 1);
    zone.bench.push({ ...basic, turnPlayed: 1 });
  }

  return { zone, mulligans };
}

export function createInitialBattle(setup: BattleSetup): BattleState {
  const seed = setup.seed ?? Date.now();
  const playerSetup = setupZone(setup.playerDeck, "player", seed);
  const opponentSetup = setupZone(setup.opponentDeck, "opponent", seed + 999);

  const state: BattleState = {
    id: `battle-${seed}`,
    turn: 1,
    currentPlayer: "player",
    winner: null,
    zones: {
      player: playerSetup.zone,
      opponent: opponentSetup.zone
    },
    energyAttachedThisTurn: { player: false, opponent: false },
    supporterUsedThisTurn: { player: false, opponent: false },
    retreatedThisTurn: { player: false, opponent: false },
    stadium: null,
    log: []
  };

  for (const [id, mulligans] of [
    ["player", playerSetup.mulligans],
    ["opponent", opponentSetup.mulligans]
  ] as const) {
    if (mulligans > 0) {
      pushLog(state, id, `${id} mulliganed ${mulligans} time(s) (no Basic Pokemon in the opening hand).`);
    }
  }

  if (playerSetup.mulligans > 0) {
    draw(state.zones.opponent, playerSetup.mulligans);
    pushLog(state, "opponent", `Drew ${playerSetup.mulligans} bonus card(s) for the player's mulligan.`);
  }
  if (opponentSetup.mulligans > 0) {
    draw(state.zones.player, opponentSetup.mulligans);
    pushLog(state, "player", `Drew ${opponentSetup.mulligans} bonus card(s) for the opponent's mulligan.`);
  }

  for (const id of playerIds) {
    if (!state.zones[id].active) {
      state.winner = id === "player" ? "opponent" : "player";
      pushLog(state, id, "No Basic Pokemon is available even after mulligans. Deck has no Basic Pokemon.");
    }
  }

  pushLog(state, "player", "Battle started. Legal actions are generated by the engine.");
  return state;
}

export function getOpponent(player: PlayerId): PlayerId {
  return player === "player" ? "opponent" : "player";
}

export function generateLegalActions(state: BattleState): LegalAction[] {
  if (state.winner) return [];

  const player = state.currentPlayer;
  const zone = state.zones[player];
  const actions: LegalAction[] = [];
  const inPlay = [zone.active, ...zone.bench].filter((card): card is BattleCard => Boolean(card));

  for (const card of zone.hand) {
    if (card.category === "pokemon" && card.isBasic && zone.bench.length < 5) {
      actions.push({ id: `play-${card.instanceId}`, type: "PLAY_BASIC", player, cardInstanceId: card.instanceId });
    }
  }

  if (!state.energyAttachedThisTurn[player]) {
    for (const card of zone.hand.filter((item) => item.category === "energy")) {
      for (const target of inPlay) {
        actions.push({
          id: `attach-${card.instanceId}-${target.instanceId}`,
          type: "ATTACH_ENERGY",
          player,
          cardInstanceId: card.instanceId,
          targetInstanceId: target.instanceId
        });
      }
    }
  }

  for (const card of zone.hand.filter((item) => item.category === "pokemon" && item.evolvesFrom)) {
    const targets = inPlay.filter(
      (target) => target.name === card.evolvesFrom && target.turnPlayed < state.turn && !target.evolvedThisTurn
    );
    for (const target of targets) {
      actions.push({
        id: `evolve-${card.instanceId}-${target.instanceId}`,
        type: "EVOLVE",
        player,
        cardInstanceId: card.instanceId,
        targetInstanceId: target.instanceId
      });
    }
  }

  for (const card of zone.hand.filter((item) => item.category === "trainer")) {
    if (card.trainerKind === "tool") continue;
    if (card.trainerKind === "supporter" && state.supporterUsedThisTurn[player]) continue;
    actions.push({ id: `trainer-${card.instanceId}`, type: "USE_TRAINER", player, cardInstanceId: card.instanceId });
  }

  for (const card of zone.hand.filter((item) => item.trainerKind === "tool")) {
    for (const target of inPlay.filter((item) => !item.tool)) {
      actions.push({
        id: `tool-${card.instanceId}-${target.instanceId}`,
        type: "ATTACH_TOOL",
        player,
        cardInstanceId: card.instanceId,
        targetInstanceId: target.instanceId
      });
    }
  }

  for (const source of inPlay.filter((item) => item.ability && !item.abilityUsedThisTurn)) {
    actions.push({
      id: `ability-${source.instanceId}-${source.ability!.id}`,
      type: "USE_ABILITY",
      player,
      sourceInstanceId: source.instanceId,
      abilityId: source.ability!.id
    });
  }

  if (zone.active && !state.retreatedThisTurn[player]) {
    const cost = zone.active.retreatCost ?? 0;
    if (zone.active.attachedEnergy >= cost) {
      for (const bench of zone.bench) {
        actions.push({
          id: `retreat-${zone.active.instanceId}-${bench.instanceId}`,
          type: "RETREAT",
          player,
          targetInstanceId: bench.instanceId
        });
      }
    }
  }

  const active = zone.active;
  if (active?.attacks && !active.evolvedThisTurn) {
    for (const attack of active.attacks) {
      if (active.attachedEnergy >= attack.cost) {
        actions.push({ id: `attack-${active.instanceId}-${attack.id}`, type: "ATTACK", player, attack });
      }
    }
  }

  actions.push({ id: `end-${state.turn}-${player}`, type: "END_TURN", player });
  return actions;
}

function removeFromHand(zone: Zone, instanceId: string): BattleCard | null {
  const index = zone.hand.findIndex((card) => card.instanceId === instanceId);
  if (index < 0) return null;
  const [card] = zone.hand.splice(index, 1);
  return card;
}

function findInPlay(zone: Zone, instanceId: string): BattleCard | null {
  if (zone.active?.instanceId === instanceId) return zone.active;
  return zone.bench.find((card) => card.instanceId === instanceId) ?? null;
}

function replaceInPlay(zone: Zone, instanceId: string, replacement: BattleCard): void {
  if (zone.active?.instanceId === instanceId) {
    zone.active = replacement;
    return;
  }
  const index = zone.bench.findIndex((card) => card.instanceId === instanceId);
  if (index >= 0) zone.bench[index] = replacement;
}

function endTurn(state: BattleState): void {
  const next = getOpponent(state.currentPlayer);
  state.currentPlayer = next;
  state.turn += 1;
  state.energyAttachedThisTurn[next] = false;
  state.supporterUsedThisTurn[next] = false;
  state.retreatedThisTurn[next] = false;
  const nextZone = state.zones[next];
  for (const card of [nextZone.active, ...nextZone.bench]) {
    if (!card) continue;
    card.evolvedThisTurn = false;
    card.abilityUsedThisTurn = false;
  }
  const drawn = draw(nextZone, 1);
  if (drawn.length === 0) {
    state.winner = getOpponent(next);
    pushLog(state, next, "Cannot draw at turn start. Deck-out loss.");
  } else {
    pushLog(state, next, `Drew 1 card. ${next} turn begins.`);
  }
}

function takePrizeOrWin(state: BattleState, player: PlayerId): void {
  const zone = state.zones[player];
  const opponent = getOpponent(player);
  const opponentZone = state.zones[opponent];
  const prize = zone.prizes.shift();
  if (prize) {
    zone.hand.push(prize);
    zone.prizeTaken += 1;
    pushLog(state, player, "Took 1 prize card.");
  }
  if (zone.prizeTaken >= 6 || opponentZone.bench.length === 0) {
    state.winner = player;
    pushLog(state, player, "Win condition reached.");
    return;
  }
  const promoted = opponentZone.bench.shift() ?? null;
  opponentZone.active = promoted;
  if (promoted) {
    pushLog(state, opponent, `${promoted.name} moved to the Active Spot.`);
  }
}

export function applyAction(current: BattleState, action: LegalAction): BattleState {
  const state: BattleState = structuredClone(current);
  if (state.winner || action.player !== state.currentPlayer) return state;

  const legal = generateLegalActions(state).some((candidate) => candidate.id === action.id);
  if (!legal) {
    pushLog(state, action.player, "Rejected illegal action.");
    return state;
  }

  const zone = state.zones[action.player];

  if (action.type === "PLAY_BASIC") {
    const card = removeFromHand(zone, action.cardInstanceId);
    if (card) {
      zone.bench.push({ ...card, turnPlayed: state.turn });
      pushLog(state, action.player, `Played ${card.name} to the Bench.`);
    }
    return state;
  }

  if (action.type === "ATTACH_ENERGY") {
    const card = removeFromHand(zone, action.cardInstanceId);
    const target = findInPlay(zone, action.targetInstanceId);
    if (card && target) {
      target.attachedEnergy += 1;
      zone.discard.push(card);
      state.energyAttachedThisTurn[action.player] = true;
      pushLog(state, action.player, `Attached energy to ${target.name}.`);
    }
    return state;
  }

  if (action.type === "EVOLVE") {
    const card = removeFromHand(zone, action.cardInstanceId);
    const target = findInPlay(zone, action.targetInstanceId);
    if (card && target) {
      const evolved: BattleCard = {
        ...card,
        instanceId: target.instanceId,
        attachedEnergy: target.attachedEnergy,
        damage: target.damage,
        tool: target.tool,
        turnPlayed: target.turnPlayed,
        previousStages: [...target.previousStages, { ...target, previousStages: [] }],
        evolvedThisTurn: true,
        abilityUsedThisTurn: false
      };
      replaceInPlay(zone, target.instanceId, evolved);
      pushLog(state, action.player, `${target.name} evolved into ${evolved.name}.`);
    }
    return state;
  }

  if (action.type === "ATTACH_TOOL") {
    const card = removeFromHand(zone, action.cardInstanceId);
    const target = findInPlay(zone, action.targetInstanceId);
    if (card && target && !target.tool) {
      target.tool = card;
      pushLog(state, action.player, `Attached ${card.name} to ${target.name}.`);
    }
    return state;
  }

  if (action.type === "USE_ABILITY") {
    const source = findInPlay(zone, action.sourceInstanceId);
    if (source?.ability && source.ability.id === action.abilityId && !source.abilityUsedThisTurn) {
      if (source.ability.effect === "drawExtra") {
        const drawn = draw(zone, 1);
        pushLog(state, action.player, `${source.name}'s ${source.ability.name} drew ${drawn.length} card.`);
      } else if (source.ability.effect === "healSelf") {
        const healed = Math.min(source.damage, 20);
        source.damage -= healed;
        pushLog(state, action.player, `${source.name}'s ${source.ability.name} healed ${healed} damage.`);
      } else if (source.ability.effect === "healBench") {
        for (const bench of zone.bench) {
          bench.damage = Math.max(0, bench.damage - 20);
        }
        pushLog(state, action.player, `${source.name}'s ${source.ability.name} healed the Bench.`);
      } else if (source.ability.effect === "energyAccel") {
        const energyIndex = zone.hand.findIndex((item) => item.category === "energy");
        if (energyIndex >= 0) {
          const [energyCard] = zone.hand.splice(energyIndex, 1);
          source.attachedEnergy += 1;
          zone.discard.push(energyCard);
          pushLog(state, action.player, `${source.name}'s ${source.ability.name} attached ${energyCard.name}.`);
        }
      }
      source.abilityUsedThisTurn = true;
    }
    return state;
  }

  if (action.type === "RETREAT") {
    const bench = zone.bench.find((card) => card.instanceId === action.targetInstanceId);
    if (zone.active && bench) {
      const cost = zone.active.retreatCost ?? 0;
      const retreating: BattleCard = { ...zone.active, attachedEnergy: Math.max(0, zone.active.attachedEnergy - cost) };
      zone.bench = zone.bench.filter((card) => card.instanceId !== bench.instanceId);
      zone.bench.push(retreating);
      zone.active = bench;
      state.retreatedThisTurn[action.player] = true;
      pushLog(state, action.player, `Retreated ${retreating.name} for ${bench.name}.`);
    }
    return state;
  }

  if (action.type === "USE_TRAINER") {
    const card = removeFromHand(zone, action.cardInstanceId);

    if (card?.trainerKind === "stadium") {
      if (state.stadium) {
        state.zones[state.stadium.owner].discard.push(state.stadium.card);
        pushLog(state, action.player, `${state.stadium.card.name} was replaced.`);
      }
      state.stadium = { card, owner: action.player };
      pushLog(state, action.player, `Played Stadium ${card.name}.`);
      return state;
    }

    if (card?.trainerEffect === "draw2") {
      const drawn = draw(zone, 2);
      pushLog(state, action.player, `Used ${card.name} and drew ${drawn.length} cards.`);
    } else if (card?.trainerEffect === "switch" && zone.bench.length > 0 && zone.active) {
      const oldActive = zone.active;
      zone.active = zone.bench.shift() ?? oldActive;
      zone.bench.push(oldActive);
      pushLog(state, action.player, `Used ${card.name} to switch Active Pokemon.`);
    } else if (card?.trainerEffect === "searchBasic") {
      const index = zone.deck.findIndex((item) => item.category === "pokemon" && item.isBasic);
      if (index >= 0 && zone.bench.length < 5) {
        const [basic] = zone.deck.splice(index, 1);
        zone.bench.push({ ...basic, turnPlayed: state.turn });
        pushLog(state, action.player, `Used ${card.name} and benched ${basic.name}.`);
      } else {
        pushLog(state, action.player, `Used ${card?.name ?? "trainer"} with no valid target.`);
      }
    }

    if (card?.trainerKind === "supporter") {
      state.supporterUsedThisTurn[action.player] = true;
    }
    if (card) zone.discard.push(card);
    return state;
  }

  if (action.type === "ATTACK") {
    const defenderZone = state.zones[getOpponent(action.player)];
    const attacker = zone.active;
    const defender = defenderZone.active;
    if (attacker && defender) {
      defender.damage += action.attack.damage;
      pushLog(state, action.player, `${attacker.name} used ${action.attack.name} for ${action.attack.damage} damage.`);
      if (defender.hp && defender.damage >= defender.hp) {
        defenderZone.discard.push(...defender.previousStages, defender);
        defenderZone.active = null;
        pushLog(state, action.player, `Knocked out ${defender.name}.`);
        takePrizeOrWin(state, action.player);
      }
    }
    if (!state.winner) endTurn(state);
    return state;
  }

  endTurn(state);
  return state;
}
